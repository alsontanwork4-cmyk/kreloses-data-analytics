stage_env() {
  stage "Vercel: production environment variables"
  if ((!VERCEL_OK)); then
    todo_item "set the production environment variables (sign in to Vercel first)"
    return 0
  fi
  load_vercel_env
  if ((!PROJECT_EXISTS)); then note "(the project does not exist yet: every variable would be new)"; fi
  say "Production only: preview deployments get none, so a preview can never touch production data."
  local name value sensitivity
  for name in $PRODUCTION_ENV_VARS; do
    if vercel_has "$name" && in_list "$name" "$ROTATE"; then
      act vercel env rm "$name" production --yes --project "$PROJECT_NAME" "${VFLAGS[@]}" || die "Could not remove the old $name."
    elif vercel_has "$name"; then
      case "$name" in
        CREDENTIALS_ENCRYPTION_KEY) done_item "$name already set: kept (never replaced)" ;;
        CRON_SECRET | MCP_BEARER_TOKEN) done_item "$name already set: kept (to replace it: scripts/deploy-wizard.sh --rotate $name)" ;;
        *) done_item "$name already set: kept (to change it: vercel env rm $name production, then run the wizard again)" ;;
      esac
      continue
    fi
    value=$(env_value "$name")
    if [[ -z "$value" ]]; then
      todo_item "$name: no value in this run"
      continue
    fi
    sensitivity=--no-sensitive
    in_list "$name" "$SENSITIVE_ENV_VARS" && sensitivity=--sensitive
    act_input "$value" vercel env add "$name" production "$sensitivity" --yes --project "$PROJECT_NAME" "${VFLAGS[@]}" ||
      die "Could not add $name (see above)."
    ENV_CHANGED=1
    ((DRY_RUN)) || done_item "$name added to Production ($sensitivity)"
  done

  for name in $LOCAL_ONLY_ENV_VARS; do
    vercel_has "$name" || continue
    warn "$name is set in production but is for local tooling/tests only (it can break or weaken the app)."
    if confirm "Remove $name from Production?"; then
      act vercel env rm "$name" production --yes --project "$PROJECT_NAME" "${VFLAGS[@]}" || die "Could not remove $name."
      ENV_CHANGED=1
      ((DRY_RUN)) || done_item "$name removed from Production"
    else
      todo_item "remove $name from Vercel Production"
    fi
  done
  note "Optional tuning, left at its defaults (README Environment variables):"
  note "  $OPTIONAL_ENV_VARS"
}

