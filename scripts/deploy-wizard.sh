# ── Values: from your environment, the saved file, or a prompt ────────────────────────────────────
VALIDATION_ERROR=""
validate() {
  local name="$1" value="$2" re
  VALIDATION_ERROR=""
  case "$name" in
    VERCEL_TEAM)
      re='^[A-Za-z0-9][A-Za-z0-9._-]*$'
      [[ "$value" =~ $re ]] || VALIDATION_ERROR="a team slug has only letters, digits, dots, dashes and underscores"
      ;;
    NEXT_PUBLIC_SUPABASE_URL)
      re='^https://[A-Za-z0-9.-]+$'
      if ! [[ "$value" =~ $re ]]; then
        VALIDATION_ERROR="expected https://<project-ref>.supabase.co (no path)"
      elif [[ "$value" == *localhost* || "$value" == *127.0.0.1* ]]; then
        VALIDATION_ERROR="that is the local stack; use the PRODUCTION project's URL"
      fi
      ;;
    NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY)
      re='^sb_publishable_[A-Za-z0-9_-]+$'
      [[ "$value" =~ $re ]] || VALIDATION_ERROR="expected the new publishable key (sb_publishable_…), not the legacy anon JWT (README Production)"
      ;;
    OWNER_EMAIL)
      re='^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
      [[ "$value" =~ $re ]] || VALIDATION_ERROR="that is not an email address"
      ;;
    SUPABASE_TRANSACTION_POOLER_URL | SUPABASE_SESSION_POOLER_URL)
      local port=6543
      [[ "$name" == SUPABASE_SESSION_POOLER_URL ]] && port=5432
      re="^postgres(ql)?://postgres(\\.[a-z0-9]+)?:\\[YOUR-PASSWORD\\]@[A-Za-z0-9.-]+:${port}/postgres(\\?.*)?\$"
      if [[ "$value" != *"$PASSWORD_PLACEHOLDER"* ]]; then
        VALIDATION_ERROR="copy it WITHOUT revealing the password: it must still contain $PASSWORD_PLACEHOLDER (the password is asked separately)"
      elif ! [[ "$value" =~ $re ]]; then
        VALIDATION_ERROR="expected postgresql://postgres.<ref>:$PASSWORD_PLACEHOLDER@<host>:${port}/postgres (port ${port})"
      fi
      ;;
    SUPABASE_DB_PASSWORD)
      if [[ "$value" == *"$PASSWORD_PLACEHOLDER"* ]]; then
        VALIDATION_ERROR="that is the placeholder, not the password"
      fi
      ;;
    PRODUCTION_URL)
      re='^https://[A-Za-z0-9.-]+$'
      [[ "$value" =~ $re ]] || VALIDATION_ERROR="expected https://<domain> (no path)"
      ;;
    GITHUB_OWNER)
      re='^[A-Za-z0-9-]+$'
      [[ "$value" =~ $re ]] || VALIDATION_ERROR="that is not a GitHub account name"
      ;;
    CRON_SECRET_FOR_GITHUB)
      [[ ${#value} -ge 16 ]] || VALIDATION_ERROR="the app's CRON_SECRET has at least 16 characters"
      ;;
  esac
  [[ -z "$VALIDATION_ERROR" ]]
}

# get_value NAME KIND PROMPT [DEFAULT]: sets V_NAME (never exported) from, in order, the exported
# environment variable NAME, the saved file, or a prompt (KIND "secret" = hidden input). Invalid
# values are refused with the reason; after three tries, or at the end of input, it stops.
get_value() {
  local name="$1" kind="$2" prompt="$3" default="${4:-}" value="" source="" tries=0
  value="${!name:-}"
  [[ -n "$value" ]] && source="your environment"
  if [[ -z "$value" ]]; then
    value=$(_existing "$name" || true)
    [[ -n "$value" ]] && source="$SAVE_FILE"
  fi
  case "$name" in *_URL) value="${value%/}" ;; esac
  if [[ -n "$value" ]] && ! validate "$name" "$value"; then
    warn "ignoring $name from $source: $VALIDATION_ERROR"
    value=""
    source=""
  fi
  while [[ -z "$value" ]]; do
    tries=$((tries + 1))
    ((tries <= 3)) || die "No valid value for $name."
    if [[ -n "$default" ]]; then
      printf '  %s%s%s %s[Enter: %s]%s ' "$BOLD" "$prompt" "$RESET" "$DIM" "$default" "$RESET"
    else
      printf '  %s%s%s ' "$BOLD" "$prompt" "$RESET"
    fi
    local answered=1
    if [[ "$kind" == secret ]]; then
      read -rs value || answered=0
      printf '\n'
    else
      read -r value || answered=0
    fi
    [[ -z "$value" && -n "$default" ]] && value="$default"
    if [[ -z "$value" && $answered -eq 0 ]]; then die "No answer for $name (end of input)."; fi
    case "$name" in *_URL) value="${value%/}" ;; esac
    if [[ -n "$value" ]] && ! validate "$name" "$value"; then
      warn "$VALIDATION_ERROR"
      value=""
    fi
  done
  if [[ -n "$source" ]]; then note "$name: from $source"; fi
  [[ "$kind" == secret ]] && register_secret "$value"
  printf -v "V_$name" '%s' "$value"
}

# ── The saved file (outside the repository, chmod 600) ─────────────────────────────────────────────
enable_save() {
  [[ "$SAVE_FILE" == /* ]] || die "DEPLOY_WIZARD_SAVE_FILE must be an absolute path."
  case "$SAVE_FILE" in "$ROOT"/*) die "Refusing to save secrets inside the repository ($SAVE_FILE)." ;; esac
  if ((DRY_RUN)); then
    planned "save the values below to $SAVE_FILE (chmod 600, outside the repository)"
    return 0
  fi
  local dir
  dir=$(dirname "$SAVE_FILE")
  [[ -d "$dir" ]] || mkdir -p -m 700 "$dir"
  (umask 077 && touch "$SAVE_FILE")
  chmod 600 "$SAVE_FILE"
  SAVE_ENABLED=1
}
save_value() {
  ((SAVE_ENABLED)) && ((!DRY_RUN)) && [[ -n "${2:-}" ]] || return 0
  write_env "$1" "$2"
  chmod 600 "$SAVE_FILE"
}

# ── Environment variable lists vs the code ─────────────────────────────────────────────────────────
# Every NAME the app's code reads as process.env.NAME, env.NAME, env?.NAME or env["NAME"].
code_env_vars() {
  # Trailing slashes: BSD grep -r does not follow a directory given as a symlink otherwise.
  local paths=("$ROOT/src/" "$ROOT/scripts/")
  [[ -f "$ROOT/next.config.ts" ]] && paths+=("$ROOT/next.config.ts")
  {
    grep -rhoE '(^|[^A-Za-z0-9_$])env\??\.[A-Z][A-Z0-9_]*' --include='*.ts' --include='*.tsx' --include='*.mts' "${paths[@]}" 2>/dev/null |
      sed -E 's/.*\.//' || true
    grep -rhoE "env\\[[\"'\`][A-Z][A-Z0-9_]*[\"'\`]\\]" --include='*.ts' --include='*.tsx' --include='*.mts' "${paths[@]}" 2>/dev/null |
      sed -E 's/^env\[.(.*).\]$/\1/' || true
  } | sort -u
}
known_env_vars() { printf '%s %s %s %s' "$PRODUCTION_ENV_VARS" "$OPTIONAL_ENV_VARS" "$LOCAL_ONLY_ENV_VARS" "$PLATFORM_ENV_VARS"; }
check_env_complete() {
  local name unknown="" known
  known=$(known_env_vars)
  for name in $(code_env_vars); do in_list "$name" "$known" || unknown="$unknown $name"; done
  if [[ -n "$unknown" ]]; then
    printf '  %s✗ The code reads environment variables this wizard does not know:%s%s\n' "$RED" "$unknown" "$RESET" >&2
    printf '    Add each to one of the lists at the top of scripts/deploy-wizard.sh (and to .env.example and\n    README "Environment variables"), then run the wizard again.\n' >&2
    return 1
  fi
  return 0
}
list_env() {
  local name
  for name in $PRODUCTION_ENV_VARS; do
    if in_list "$name" "$SENSITIVE_ENV_VARS"; then printf 'production %s sensitive\n' "$name"; else printf 'production %s plain\n' "$name"; fi
  done
  for name in $OPTIONAL_ENV_VARS; do printf 'optional %s\n' "$name"; done
  for name in $LOCAL_ONLY_ENV_VARS; do printf 'local %s\n' "$name"; done
  for name in $PLATFORM_ENV_VARS; do printf 'platform %s\n' "$name"; done
}

