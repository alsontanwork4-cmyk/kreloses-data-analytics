generate_secret() {
  local name="$1" format="$2" value
  if ((DRY_RUN)); then
    planned "openssl rand -$format 32   (the new $name, kept in memory, never shown)"
    printf -v "V_$name" '%s' "dry-run-placeholder-$name"
    NEW_SECRETS="$NEW_SECRETS $name"
    return 0
  fi
  value=$(probe openssl rand "-$format" 32 | tr -d '\n')
  [[ ${#value} -ge 32 ]] || die "openssl did not produce a usable $name."
  register_secret "$value"
  printf -v "V_$name" '%s' "$value"
  NEW_SECRETS="$NEW_SECRETS $name"
  done_item "generated a new $name (openssl rand -$format 32; not shown)"
}

stage_secrets() {
  stage "Secrets: encryption key, cron secret, MCP token"
  load_vercel_env
  local name format saved
  for name in CREDENTIALS_ENCRYPTION_KEY CRON_SECRET MCP_BEARER_TOKEN; do
    format=base64
    [[ "$name" == CRON_SECRET ]] && format=hex # README: openssl rand -hex 32
    saved=$(_existing "$name" || true)
    if in_list "$name" "$ROTATE"; then
      say "Rotating $name (--rotate): a new one replaces the one in Vercel in stage 6."
      generate_secret "$name" "$format"
      continue
    fi
    if vercel_has "$name"; then
      if [[ "$name" == CREDENTIALS_ENCRYPTION_KEY ]]; then
        done_item "CREDENTIALS_ENCRYPTION_KEY is already set in Vercel: kept (never replaced; a new key would make every saved Kreloses password unreadable)"
      else
        done_item "$name is already set in Vercel: kept"
      fi
      if [[ -n "$saved" ]]; then
        register_secret "$saved"
        printf -v "V_$name" '%s' "$saved"
      fi
      continue
    fi
    if [[ -n "$saved" ]]; then
      register_secret "$saved"
      printf -v "V_$name" '%s' "$saved"
      NEW_SECRETS="$NEW_SECRETS $name"
      done_item "$name: reusing the one generated by an earlier run ($SAVE_FILE); not in Vercel yet"
    else
      generate_secret "$name" "$format"
    fi
  done

  [[ -n "$NEW_SECRETS" ]] || return 0
  say ""
  if ((SAVE_ENABLED)); then
    note "Keeping them in $SAVE_FILE (readable only by you)."
  elif confirm "Save a copy of the new secrets and your settings to $SAVE_FILE (outside the repository, chmod 600)? You need the MCP token later to connect Claude."; then
    enable_save
  else
    note "Not saved. Vercel stores them write-only, so keep your own copy of the MCP token now."
    if command -v pbcopy >/dev/null 2>&1 && [[ -n "${V_MCP_BEARER_TOKEN:-}" ]] && in_list MCP_BEARER_TOKEN "$NEW_SECRETS" && ((!DRY_RUN)) &&
      confirm "Copy the MCP token to the clipboard (paste it into your password manager)?"; then
      printf '%s' "$V_MCP_BEARER_TOKEN" | pbcopy
      done_item "MCP token copied to the clipboard (not shown)"
    fi
  fi
  for name in $NEW_SECRETS; do
    local holder="V_$name"
    save_value "$name" "${!holder:-}"
  done
  save_value VERCEL_TEAM "${V_VERCEL_TEAM:-}"
}

