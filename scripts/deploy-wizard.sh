stage_deploy() {
  stage "Deploy to production"
  if ((!VERCEL_OK)); then
    todo_item "deploy to production (sign in to Vercel first)"
    return 0
  fi
  local known_url="${PRODUCTION_URL:-}"
  [[ -n "$known_url" ]] || known_url=$(_existing PRODUCTION_URL || true)
  known_url="${known_url%/}"
  if [[ -n "$known_url" ]] && site_answers "$known_url"; then
    say "A production deployment already answers at $known_url."
    if ((ENV_CHANGED)); then
      say "Environment variables changed in this run: only a new deployment picks them up."
      if ! confirm "Deploy now?"; then
        todo_item "deploy again so the new environment variables apply"
        get_value PRODUCTION_URL text "Production URL:" "$known_url"
        return 0
      fi
    elif ! confirm "Deploy again anyway?"; then
      done_item "production deployment answering at $known_url"
      get_value PRODUCTION_URL text "Production URL:" "$known_url"
      save_value PRODUCTION_URL "$V_PRODUCTION_URL"
      return 0
    fi
  else
    say "Uploads this checkout (the clean main checked in stage 1; .vercelignore keeps local files such as"
    say ".env files and .claude/ out) and builds it on Vercel. Later pushes to main deploy by themselves."
    if ! confirm "Create the production deployment now?"; then
      todo_item "deploy to production (vercel deploy --prod)"
      return 0
    fi
  fi
  local deployment="" default_url="" aliases=""
  act_capture deployment vercel deploy --prod --yes --project "$PROJECT_NAME" "${VFLAGS[@]}" || die "vercel deploy failed: see the build output above."
  deployment=$(printf '%s\n' "$deployment" | grep -E '^https://' | tail -n 1 || true)
  if [[ -n "$deployment" ]]; then
    done_item "deployed: $deployment"
    aliases=$(probe vcs api "/v13/deployments/${deployment#https://}" --raw 2>/dev/null | jq -r '(.alias // [])[]' 2>/dev/null || true)
    # Prefer a custom domain, else the shortest *.vercel.app alias (the production domain).
    default_url=$(printf '%s\n' "$aliases" | grep -v '\.vercel\.app$' | grep . | head -n 1 || true)
    [[ -n "$default_url" ]] || default_url=$(printf '%s\n' "$aliases" | grep . | awk '{ print length, $0 }' | sort -n | head -n 1 | cut -d' ' -f2- || true)
    [[ -z "$default_url" ]] || default_url="https://$default_url"
  fi
  [[ -n "$default_url" ]] || default_url="$known_url"
  step "The production URL is the project's domain (Vercel → $PROJECT_NAME → Settings → Domains), not the"
  step "deployment's own URL above (that one sits behind Deployment Protection)."
  if ((DRY_RUN)) && [[ -z "${PRODUCTION_URL:-}$default_url" ]]; then
    note "(dry run: no production URL yet; later stages show placeholders)"
    return 0
  fi
  get_value PRODUCTION_URL text "Production URL:" "$default_url"
  save_value PRODUCTION_URL "$V_PRODUCTION_URL"
}

