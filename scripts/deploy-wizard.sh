stage_preflight() {
  stage "Preflight: tools and the code to deploy"
  say "Checks this machine and the checkout. Changes nothing."
  local tool missing="" problems=""
  for tool in node npm git supabase vercel gh openssl curl jq; do
    command -v "$tool" >/dev/null 2>&1 || missing="$missing $tool"
  done
  if [[ -n "$missing" ]]; then
    warn "missing:$missing"
    note "Node 22+: https://nodejs.org · Supabase CLI: brew install supabase/tap/supabase · Vercel CLI: npm i -g vercel"
    note "GitHub CLI: brew install gh · openssl, curl and jq ship with macOS (brew install jq otherwise)"
    die "Install the missing tools, then run the wizard again."
  fi
  local node_major
  node_major=$(probe node -v 2>/dev/null | sed -E 's/^v([0-9]+).*/\1/')
  [[ "$node_major" =~ ^[0-9]+$ ]] && ((node_major >= 22)) || die "Node.js 22 or newer is needed (found: $(probe node -v 2>/dev/null || echo none))."
  done_item "tools: node $node_major, npm, git, supabase, vercel, gh, openssl, curl, jq"

  check_env_complete || die "The environment variable list is out of date (see above)."
  done_item "every environment variable the code reads is known to this wizard"

  local remote re='github\.com[:/]([^/]+)/([^/]+)$'
  remote=$(probe git -C "$ROOT" remote get-url origin 2>/dev/null || true)
  if [[ "$remote" =~ $re ]]; then
    REPO_OWNER="${BASH_REMATCH[1]}"
    REPO_SLUG="$REPO_OWNER/${BASH_REMATCH[2]%.git}"
  else
    die "The 'origin' remote is not a GitHub repository ($remote)."
  fi

  local branch dirty head upstream
  branch=$(probe git -C "$ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || true)
  dirty=$(probe git -C "$ROOT" status --porcelain 2>/dev/null || true)
  probe git -C "$ROOT" fetch --quiet origin main 2>/dev/null || warn "could not fetch origin/main (offline?)"
  head=$(probe git -C "$ROOT" rev-parse HEAD 2>/dev/null || true)
  upstream=$(probe git -C "$ROOT" rev-parse origin/main 2>/dev/null || true)
  [[ "$branch" == main ]] || problems="$problems\n    on branch '$branch', not main: git switch main"
  [[ -z "$dirty" ]] || problems="$problems\n    uncommitted changes: commit or stash them (git status)"
  [[ -n "$head" && "$head" == "$upstream" ]] || problems="$problems\n    not the latest main: git pull --ff-only"
  if [[ -n "$problems" ]]; then
    printf '  %s⚠ The checkout is not a clean, up-to-date main:%b%s\n' "$YELLOW" "$problems" "$RESET"
    ((DRY_RUN)) || die "Deploy only the latest main. Fix the above, then run the wizard again."
    todo_item "deploy from a clean, up-to-date main"
  else
    done_item "clean checkout of the latest main ($REPO_SLUG)"
  fi

  say ""
  say "Optional: install exactly the locked dependencies and run the typecheck and the tests first."
  note "(npm test needs the local Supabase stack running: 'supabase status'. Skip it if you don't run it locally.)"
  if confirm "Run npm ci, npm run typecheck and npm test now?"; then
    act npm ci || die "npm ci failed."
    act npm run typecheck || die "The typecheck failed: don't deploy this checkout."
    act npm test || die "The tests failed: don't deploy this checkout."
    ((DRY_RUN)) || done_item "npm ci, typecheck and tests passed"
  fi
}

