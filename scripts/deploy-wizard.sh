# ── Running commands: probes read, actions change ─────────────────────────────────────────────────
# A probe only reads (who am I signed in as, which variables exist, an HTTP status). It runs in
# every mode, including --dry-run, with stdin closed so it can never swallow an answer.
probe() { "$@" </dev/null; }

# The command as you could type it, each argument masked BEFORE any quoting (so quoting can never
# change a secret into something the mask misses), quoted only when the shell would need it.
cmd_text() {
  local text="" arg plain='^[A-Za-z0-9_./:=@%+,<>-]+$'
  for arg in "$@"; do
    arg=$(mask "$arg")
    if [[ "$arg" =~ $plain ]]; then text="$text $arg"; else text="$text $(printf '%q' "$arg")"; fi
  done
  printf '%s%s' "$DISPLAY_PREFIX" "${text# }"
}
show_cmd() { printf '  %s$ %s%s\n' "$DIM" "$(mask "$1")" "$RESET"; }
planned() {
  PLANNED+=("$(mask "$1")")
  printf '  %s[dry-run]%s %s\n' "$YELLOW" "$RESET" "$(mask "$1")"
}
# Last line of defence for spec rule #1: the production CREDENTIALS_ENCRYPTION_KEY is never
# replaced, updated or removed by this wizard (a new key makes every stored Kreloses password unreadable).
guard_command() {
  if [[ "$1" == *CREDENTIALS_ENCRYPTION_KEY* ]]; then
    case "$1" in
      *" rm "* | *" remove "* | *" update "* | *--force*) die "Refusing to change the production CREDENTIALS_ENCRYPTION_KEY." ;;
    esac
    if [[ "$1" == *"env add"* ]] && in_list CREDENTIALS_ENCRYPTION_KEY "$VERCEL_ENV_KEYS"; then
      die "Refusing to add a second CREDENTIALS_ENCRYPTION_KEY: production already has one."
    fi
  fi
  return 0
}
# act CMD...: changes something (Vercel, Supabase, GitHub, a local file). --dry-run prints it instead.
act() {
  local text
  text=$(cmd_text "$@")
  guard_command "$text"
  if ((DRY_RUN)); then
    planned "$text"
    return 0
  fi
  show_cmd "$text"
  "$@" </dev/null
}
# act_tty CMD...: like act, for a command that may ask its own questions (keeps the terminal).
act_tty() {
  local text
  text=$(cmd_text "$@")
  guard_command "$text"
  if ((DRY_RUN)); then
    planned "$text"
    return 0
  fi
  show_cmd "$text"
  "$@"
}
# act_input VALUE CMD...: like act, with VALUE on the command's stdin. This is how every secret
# reaches vercel and gh: never as an argument (arguments show in process lists and on screen).
act_input() {
  local value="$1" text
  shift
  text="$(cmd_text "$@") < (value on stdin, hidden)"
  guard_command "$text"
  if ((DRY_RUN)); then
    planned "$text"
    return 0
  fi
  show_cmd "$text"
  printf '%s' "$value" | "$@"
}
# act_capture VAR CMD...: like act; the command's stdout goes into VAR (its stderr still shows).
act_capture() {
  local var="$1" text output
  shift
  text=$(cmd_text "$@")
  guard_command "$text"
  printf -v "$var" '%s' ""
  if ((DRY_RUN)); then
    planned "$text"
    return 0
  fi
  show_cmd "$text"
  output=$("$@" </dev/null) || return $?
  printf -v "$var" '%s' "$output"
}

