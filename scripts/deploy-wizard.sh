# ── HTTP checks (stage 10 and --check) ─────────────────────────────────────────────────────────────
HTTP_STATUS=""
http_request() {
  local url="$1"
  shift
  local proto=()
  [[ "$url" == https://* ]] && proto=(--proto '=https')
  : >"$TMP_DIR/body"
  : >"$TMP_DIR/headers"
  HTTP_STATUS=$(curl -sS ${proto[@]+"${proto[@]}"} --max-time 30 -o "$TMP_DIR/body" -D "$TMP_DIR/headers" -w '%{http_code}' "$@" "$url" </dev/null 2>"$TMP_DIR/error") || true
  [[ -n "$HTTP_STATUS" ]] || HTTP_STATUS=000
}
body_has() { grep -qF -- "$1" "$TMP_DIR/body"; }
header_has() { grep -qiE -- "$1" "$TMP_DIR/headers"; }
check_pass() { printf '  %s✓%s %s\n' "$GREEN" "$RESET" "$1"; }
check_fail() {
  printf '  %s✗ %s%s\n' "$RED" "$1" "$RESET"
  [[ -n "${2:-}" ]] && printf '    %s\n' "$2"
  CHECK_FAILURES=$((CHECK_FAILURES + 1))
}
is_loopback_url() {
  local re='^http://(localhost|127\.0\.0\.1|\[::1\])(:[0-9]+)?$'
  [[ "$1" =~ $re ]]
}
site_answers() {
  http_request "${1%/}/login"
  [[ "$HTTP_STATUS" == 200 ]] && body_has "$LOGIN_PAGE_MARKER"
}

# run_checks URL: read-only requests, no secrets sent. Returns 1 if any check failed.
CHECK_FAILURES=0
run_checks() {
  local base="${1%/}" host
  CHECK_FAILURES=0
  if [[ "$base" == https://* ]]; then
    host="${base#https://}"
    http_request "http://$host/login"
    if [[ "$HTTP_STATUS" == 30[178] ]] && header_has "^location: *https://"; then
      check_pass "plain HTTP redirects to HTTPS"
    else
      check_fail "http://$host answered $HTTP_STATUS (expected a redirect to https://)"
    fi
  elif is_loopback_url "$base"; then
    note "local URL: HTTPS not checked"
  else
    check_fail "$base is not HTTPS" "Production must be served over https://"
    return 1
  fi

  http_request "$base/login"
  if [[ "$HTTP_STATUS" == 200 ]] && body_has "$LOGIN_PAGE_MARKER"; then
    check_pass "/login renders the sign-in page (HTTPS reachable)"
  elif [[ "$HTTP_STATUS" == 000 ]]; then
    check_fail "$base is not reachable: $(mask "$(head -c 300 "$TMP_DIR/error")")" "Is the URL right, and has the deploy finished?"
  elif [[ "$HTTP_STATUS" == 401 || "$HTTP_STATUS" == 403 ]]; then
    check_fail "/login answered $HTTP_STATUS" "Vercel Deployment Protection covers this URL. Use the production domain (Standard Protection leaves it public) or check Settings → Deployment Protection."
  else
    check_fail "/login answered HTTP $HTTP_STATUS without the sign-in page" "Look at the deployment's logs in Vercel (missing environment variables?)."
  fi

  http_request "$base/overview"
  if [[ "$HTTP_STATUS" == 30[278] ]] && header_has "^location: *[^ ]*/login"; then
    check_pass "signed-out visitors are sent to /login (the dashboard is private)"
  else
    check_fail "/overview answered $HTTP_STATUS to a signed-out visitor (expected a redirect to /login)"
  fi

  check_cron_endpoint "$base" /api/cron/nightly "nightly sync"
  if [[ -f "$ROOT/src/app/api/cron/backfill/route.ts" ]]; then
    check_cron_endpoint "$base" /api/cron/backfill "history backfill"
  fi

  http_request "$base/api/mcp" -X POST -H 'Content-Type: application/json' -H 'Accept: application/json, text/event-stream' \
    --data '{"jsonrpc":"2.0","id":1,"method":"tools/list"}'
  if [[ "$HTTP_STATUS" == 401 ]] && header_has '^www-authenticate: *Bearer realm="kreloses-mcp"'; then
    check_pass "/api/mcp answers 401 without the token (MCP_BEARER_TOKEN is set)"
  elif [[ "$HTTP_STATUS" == 503 ]]; then
    check_fail "/api/mcp answered 503: MCP_BEARER_TOKEN is not set on the server" "Set it (stage 6) and deploy again."
  else
    check_fail "/api/mcp answered $HTTP_STATUS without a token (expected 401 with WWW-Authenticate: Bearer)"
  fi

  if ((CHECK_FAILURES)); then return 1; fi
  return 0
}
check_cron_endpoint() {
  local base="$1" path="$2" what="$3"
  http_request "$base$path"
  if [[ "$HTTP_STATUS" == 401 ]] && body_has '"unauthorized"'; then
    check_pass "$path answers 401 without the cron secret ($what)"
  elif [[ "$HTTP_STATUS" == 401 ]] && body_has '"unauthenticated"'; then
    check_fail "$path is behind the sign-in gate" "The deployed code predates this endpoint: deploy the latest main."
  elif [[ "$HTTP_STATUS" == 2* ]]; then
    check_fail "$path answered $HTTP_STATUS WITHOUT the secret" "Stop and investigate: this endpoint must refuse unauthenticated calls."
  else
    check_fail "$path answered $HTTP_STATUS (expected 401)"
  fi
}

